#!/usr/bin/env node
/**
 * Compile .kb/procedures/*.md into per-harness adapters.
 *
 *   node .kb/bin/install-knowledge.mjs [--check] [--harness all|claude,copilot,windsurf,agents,devin]
 *
 * The adapters make each agent's FIRST DRAFT right. They are not, and cannot
 * be, an enforcement mechanism — an agent may decline to run a command, invent
 * arguments, or summarise output instead of applying it. `kb verify` in CI is
 * the contract (docs/adrs/008-interfaces-and-runtime.md), and every adapter says so.
 *
 * Generated; never hand-edited. `kb verify` reports a stale adapter as KB014,
 * exactly as it reports a stale index.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const KB_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = path.resolve(KB_DIR, '..');

// The tightest documented cap across the four surfaces is Windsurf's 6,000-char
// global rules file. Budgeting to it keeps one body portable everywhere.
const RULE_BUDGET = 6000;

// Agent Skills spec fields. Claude Code accepts many more, but claude.ai uploads
// and the Skills API hard-error on anything outside these six.
const SPEC_FIELDS = ['name', 'description', 'license', 'compatibility', 'metadata', 'allowed-tools'];

const MARK_START = '<!-- BEGIN kb-pipeline (generated by .kb/bin/install-knowledge.mjs) -->';
const MARK_END = '<!-- END kb-pipeline -->';

export function loadProcedures(kbDir = KB_DIR) {
  const dir = path.join(kbDir, 'procedures');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
    if (!m) throw new Error(`procedure ${f} has no frontmatter`);
    return { ...parseYaml(m[1]), body: text.slice(m[0].length).trim(), file: f };
  });
}

const contractNote =
  'The contract is `kb verify` in CI, not this file. If a command refuses, read the ' +
  'remedy in its JSON output and act on that. Policy: `.kb/POLICY.md`.';

const yamlScalar = (v) => (/^[A-Za-z0-9][A-Za-z0-9 ._/,()-]*$/.test(v) ? v : JSON.stringify(v));

/** Claude Code / Devin / Windsurf all take this shape. Six frontmatter fields only. */
function skillFile(p) {
  const fm = SPEC_FIELDS
    .filter((k) => p[k] !== undefined)
    .map((k) => `${k}: ${yamlScalar(String(p[k]))}`)
    .join('\n');
  return `---\n${fm}\n---\n\n# ${p.name}\n\n\`${p.verb}\`\n\n${p.body}\n\n---\n\n${contractNote}\n`;
}

function copilotFile(p) {
  // applyTo is required on .instructions.md; without it the file is inert.
  return `---\napplyTo: ${yamlScalar(p.paths ?? '**/*.md')}\n---\n\n` +
         `# ${p.name}\n\n${p.description}\n\n\`${p.verb}\`\n\n${p.body}\n\n---\n\n${contractNote}\n`;
}

function windsurfRule(p) {
  const head = `---\ntrigger: model_decision\ndescription: ${yamlScalar(p.description)}\n---\n\n`;
  const full = `${head}\`${p.verb}\`\n\n${p.body}\n\n${contractNote}\n`;
  if (full.length <= RULE_BUDGET) return full;
  // Over budget: degrade to a pointer at the full skill rather than truncating
  // mid-sentence, which would leave a rule that reads as complete but is not.
  return `${head}\`${p.verb}\`\n\n${p.description}\n\n` +
         `Full procedure: \`.windsurf/skills/${p.name}/SKILL.md\`.\n\n${contractNote}\n`;
}

function agentsSection(procs) {
  const rows = procs.map((p) => `| \`${p.verb}\` | ${p.description} |`).join('\n');
  return [
    MARK_START,
    '',
    '## Knowledge pipeline (`kb`)',
    '',
    'This repository is a knowledge base maintained through a `kb` CLI. **`kb` never calls a model.**',
    'Commands that need judgment run in two phases: without a draft they emit a self-contained JSON',
    'task, and with one they validate your answer and act on it deterministically. You supply the',
    'judgment; the CLI supplies the structure and every decision that can be made by rule.',
    '',
    '| command | use it when |',
    '|---|---|',
    rows,
    '',
    '**Rules that are not negotiable** (`.kb/POLICY.md`):',
    '',
    '- Never delete or rewrite a wikilink. An unresolved link is a recorded gap, not an error.',
    '- Never modify text inside inline code spans or fenced code blocks.',
    '- Never delete a file. A `discard` verdict is a recommendation.',
    '- Bulk writers dry-run by default; `--apply` needs a clean tree so the change stays reviewable.',
    '',
    '**Supplier economics** (ADR-014): every emitted task carries an advisory `cognition` grade — `mechanical` tasks suit your cheapest competent model, `composition` a mid tier, `judgment` the strongest you can afford, because that answer becomes canon. And regardless of tier: tasks are self-contained by design, so run them in **short-lived workers** (one or a few tasks each) — a single long-lived agent looping over many items re-reads its own growing transcript on every turn and pays for it.',
    '',
    'Run `kb verify` before committing. It is the contract — CI runs it, and these instructions cannot enforce anything.',
    '',
    MARK_END,
  ].join('\n');
}

/** Idempotent marker-managed write: leaves any hand-written content around it. */
function spliceMarked(existing, section) {
  if (!existing) return `${section}\n`;
  const s = existing.indexOf(MARK_START);
  const e = existing.indexOf(MARK_END);
  if (s === -1 || e === -1) return `${existing.trimEnd()}\n\n${section}\n`;
  return existing.slice(0, s) + section + existing.slice(e + MARK_END.length);
}

/** Every file the generator owns, as {path: content}. Pure — the check mode compares against it. */
export function render(procs, root = ROOT) {
  const out = {};
  for (const p of procs) {
    out[`.claude/skills/${p.name}/SKILL.md`] = skillFile(p);
    out[`.agents/skills/${p.name}/SKILL.md`] = skillFile(p);
    out[`.windsurf/skills/${p.name}/SKILL.md`] = skillFile(p);
    out[`.windsurf/rules/${p.name}.md`] = windsurfRule(p);
    out[`.github/instructions/${p.name}.instructions.md`] = copilotFile(p);
  }

  const section = agentsSection(procs);
  const agentsPath = path.join(root, 'AGENTS.md');
  out['AGENTS.md'] = spliceMarked(fs.existsSync(agentsPath) ? fs.readFileSync(agentsPath, 'utf8') : null, section);

  // Claude Code does not read AGENTS.md — it needs an import, not a symlink,
  // so Claude-specific content can live alongside it.
  const claudePath = path.join(root, 'CLAUDE.md');
  const claudeBody = '@AGENTS.md\n\nSkills for each pipeline command are in `.claude/skills/`.\n';
  out['CLAUDE.md'] = spliceMarked(
    fs.existsSync(claudePath) ? fs.readFileSync(claudePath, 'utf8') : null,
    `${MARK_START}\n\n${claudeBody}\n${MARK_END}`,
  );
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const files = render(loadProcedures());

  const stale = [];
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(ROOT, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (current === content) continue;
    stale.push(rel);
    if (!check) {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content);
    }
  }

  const payload = { ok: !(check && stale.length), checked: check, files: Object.keys(files).length, stale };
  if (process.stdout.isTTY && !args.includes('--format')) {
    console.log(stale.length
      ? `${check ? 'stale' : 'wrote'} ${stale.length}/${Object.keys(files).length} adapter file(s)`
      : `adapters up to date (${Object.keys(files).length} files)`);
  } else {
    console.log(JSON.stringify(payload, null, 2));
  }
  process.exitCode = payload.ok ? 0 : 1;
}

if (import.meta.url === `file://${process.argv[1]}`) main();
